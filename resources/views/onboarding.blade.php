    $(document).ready(function(){
        const slider = $("#new-slider").owlCarousel({
            loop:true,
            margin:10000,
            nav:true,
            items: 1,
            navText:
                ["<img src='./dist/images/slider-prev.png'>","<img src='./dist/images/slider-next.png'>"],
        });

        // Получаем количество реальных слайдов (без клонов)
        var realItems = $('.owl-carousel .owl-item:not(.cloned)').length;
        var lastSlideIndex = realItems - 1;
        var isLastSlide = false;

        slider.on('changed.owl.carousel', function(event) {
            var current = event.page.index;

            // Если текущий слайд последний - устанавливаем флаг
            if (current === lastSlideIndex) {
                isLastSlide = true;
            }
            // Если был последний слайд и теперь первый - это переход по loop
            else if (current === 0 && isLastSlide) {
                setTimeout(function() {
                    window.location.href = '/onboarding_finish';
                }, 50);
                isLastSlide = false; // Сбрасываем флаг
            }
            // В других случаях сбрасываем флаг
            else {
                isLastSlide = false;
            }
        });
    });
